// Extract actual CMU activity captures; no external code is executed.
import fs from 'node:fs';
import * as T from 'three';
import { BVHLoader } from 'three/addons/loaders/BVHLoader.js';
const names={spine_01:'LowerBack',spine_02:'Spine',spine_03:'Spine1',neck_01:'Neck1',head:'Head'};
const data={};
for(const [mode,id,start,end]of [['coffee','79_38',.5,4.45],['painting','79_43',1.4,7.15],['typing','79_85',2.5,5.8]]){
 const {skeleton,clip}=new BVHLoader().parse(fs.readFileSync(new URL(`./cmu-${id}.bvh`,import.meta.url),'utf8'));
 const root=skeleton.bones[0],mixer=new T.AnimationMixer(root),action=mixer.clipAction(clip).play();
 const sample=t=>{action.time=t;mixer.update(0);root.updateMatrixWorld(true);};
 const pos=n=>root.getObjectByName(n).getWorldPosition(new T.Vector3());
 sample(.5);
 const ref=Object.fromEntries(Object.entries(names).map(([n,s])=>[n,root.getObjectByName(s).getWorldQuaternion(new T.Quaternion()).invert()]));
 // The conversion writes 120 Hz for all files. CMU subject 79 was captured
 // at 60 Hz: retaining the actual capture rate prevents doubled-speed motion.
 const duration=(end-start)*2,count=Math.ceil(duration*30),frames=[];
 for(let i=0;i<=count;i++){
  sample(start+(end-start)*i/count);const hip=pos('Hips');
  frames.push({rotations:Object.fromEntries(Object.entries(names).map(([n,s])=>[n,root.getObjectByName(s).getWorldQuaternion(new T.Quaternion()).multiply(ref[n]).toArray()])),
   hands:Object.fromEntries(['Left','Right'].map(side=>[side,pos(side+'Hand').sub(hip).multiplyScalar(.056444).toArray()])),
   elbows:Object.fromEntries(['Left','Right'].map(side=>[side,pos(side+'ForeArm').sub(hip).multiplyScalar(.056444).toArray()]))});
 }
 // Close the cropped loop gradually, preserving the recorded variations.
 for(let i=0;i<count;i++){
  const u=i/count,w=u*u*u*(10+u*(-15+6*u));
  for(const type of ['hands','elbows'])for(const side of ['Left','Right']){
   const delta=new T.Vector3().fromArray(frames[0][type][side]).sub(new T.Vector3().fromArray(frames[count][type][side]));
   frames[i][type][side]=new T.Vector3().fromArray(frames[i][type][side]).addScaledVector(delta,w).toArray();
  }
  for(const n of Object.keys(names)){
   const mismatch=new T.Quaternion().fromArray(frames[count].rotations[n]).invert().multiply(new T.Quaternion().fromArray(frames[0].rotations[n]));
   frames[i].rotations[n]=new T.Quaternion().fromArray(frames[i].rotations[n]).multiply(new T.Quaternion().slerp(mismatch,w)).toArray();
  }
 }
 frames[count]=structuredClone(frames[0]);data[mode]={source:`CMU ${id}`,duration,count,frames};
}
fs.writeFileSync(new URL('./activity-clips.js',import.meta.url),'// Generated by prepare-activities.mjs; see CREDITS.md.\nexport const ACTIVITY_CLIPS='+JSON.stringify(data,(_k,v)=>typeof v==='number'?+v.toFixed(6):v)+';\n');
console.log(Object.fromEntries(Object.entries(data).map(([n,c])=>[n,{source:c.source,seconds:c.duration,frames:c.count+1}])));
