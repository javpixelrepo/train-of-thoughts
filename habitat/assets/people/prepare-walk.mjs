// Data conversion only. Source: CMU 07_01, BVH conversion by Bruce Hahne.
// Produces a small periodic, heading-normalized cycle for the existing rigs.
import fs from 'node:fs';
import * as T from 'three';
import { BVHLoader } from 'three/addons/loaders/BVHLoader.js';
const source=new BVHLoader().parse(fs.readFileSync(new URL('./cmu-07-01.bvh',import.meta.url),'utf8'));
const root=source.skeleton.bones[0],mixer=new T.AnimationMixer(root),action=mixer.clipAction(source.clip).play();
const V=()=>new T.Vector3(),Q=()=>new T.Quaternion(),up=new T.Vector3(0,1,0);
const names={pelvis:'Hips',spine_01:'LowerBack',spine_02:'Spine',spine_03:'Spine1',neck_01:'Neck1',head:'Head'};
function sample(t){action.time=t;mixer.update(0);root.updateMatrixWorld(true);}
function position(n){return root.getObjectByName(n).getWorldPosition(V());}
sample(0);
const reference=Object.fromEntries(Object.entries(names).map(([target,n])=>[target,root.getObjectByName(n).getWorldQuaternion(Q()).invert()]));
const start=.575,duration=1.05,count=126,scale=.056444;
sample(start);const begin=position('Hips');sample(start+duration);const end=position('Hips');
const heading=Math.atan2(end.x-begin.x,end.z-begin.z),unheading=Q().setFromAxisAngle(up,-heading);
const frames=[];
for(let i=0;i<=count;i++){
 const t=i/count;sample(start+t*duration);const hip=position('Hips'),linear=begin.clone().lerp(end,t);
 const frame={offset:hip.clone().sub(linear).multiplyScalar(scale).applyQuaternion(unheading).toArray(),rotations:{},arms:{},feet:{}};
 for(const [target,n]of Object.entries(names))frame.rotations[target]=unheading.clone().multiply(root.getObjectByName(n).getWorldQuaternion(Q())).multiply(reference[target]).toArray();
 for(const [side,label]of [['l','Left'],['r','Right']]){
  const shoulder=position(label+'Arm'),elbow=position(label+'ForeArm'),wrist=position(label+'Hand');
  frame.arms[side]={upper:elbow.clone().sub(shoulder).normalize().applyQuaternion(unheading).toArray(),lower:wrist.clone().sub(elbow).normalize().applyQuaternion(unheading).toArray()};
  const ankle=position(label+'Foot'),toe=position(label+'ToeBase');
  frame.feet[side]={position:ankle.clone().sub(linear).multiplyScalar(scale).applyQuaternion(unheading).toArray(),pitch:-Math.atan2(toe.y-ankle.y,Math.hypot(toe.x-ankle.x,toe.z-ankle.z))};
 }
 frames.push(frame);
}
// Distribute the tiny cycle mismatch over the cycle; don't add a crossfade
// that moves a planted foot. Foot contacts are handled separately at runtime.
for(const target of Object.keys(names)){
 const first=Q().fromArray(frames[0].rotations[target]),last=Q().fromArray(frames[count].rotations[target]);
 const mismatch=last.clone().invert().multiply(first);
 for(let i=0;i<=count;i++){
  const q=Q().fromArray(frames[i].rotations[target]);q.multiply(Q().slerp(mismatch,i/count));frames[i].rotations[target]=q.toArray();
 }
}
for(const side of ['l','r'])for(const segment of ['upper','lower']){
 const first=V().fromArray(frames[0].arms[side][segment]),last=V().fromArray(frames[count].arms[side][segment]),delta=first.sub(last);
 for(let i=0;i<=count;i++)frames[i].arms[side][segment]=V().fromArray(frames[i].arms[side][segment]).addScaledVector(delta,i/count).normalize().toArray();
}
const mean=frames.slice(0,count).reduce((sum,f)=>sum.add(V().fromArray(f.offset)),V()).multiplyScalar(1/count);
frames.forEach(f=>f.offset=V().fromArray(f.offset).sub(mean).toArray());
// Swing arc sampled from the recorded right step. Its progress and lift are
// independent of limb length and can be scaled without synthetic sine arcs.
const arc=[];const takeoff=.06,landing=.462;
sample(start+takeoff);const a=position('RightFoot');sample(start+landing);const b=position('RightFoot');
for(let i=0;i<=60;i++){
 const u=i/60;sample(start+takeoff+(landing-takeoff)*u);const p=position('RightFoot'),toe=position('RightToeBase');
 arc.push([T.MathUtils.clamp((p.z-a.z)/(b.z-a.z),0,1),Math.max(0,(p.y-T.MathUtils.lerp(a.y,b.y,u))*scale),-Math.atan2(toe.y-p.y,toe.z-p.z)]);
}
const data={source:'CMU 07_01 / Bruce Hahne BVH',duration,count,frames,arc};
fs.writeFileSync(new URL('./walk-cycle.js',import.meta.url),'// Generated by prepare-walk.mjs; see CREDITS.md.\nexport const WALK_CYCLE = '+JSON.stringify(data,(_k,v)=>typeof v==='number'?+v.toFixed(6):v)+';\n');
console.log({frames:frames.length,heading,maxLift:Math.max(...arc.map(x=>x[1])),size:fs.statSync(new URL('./walk-cycle.js',import.meta.url)).size});
